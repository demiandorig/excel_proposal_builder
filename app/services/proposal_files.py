"""
A durable, shared copy of a generated proposal's files.

Why this exists: /api/generate writes the .xlsx into PROPOSALS_DIR on the LOCAL disk of whichever server instance
handled that request, and stores only the file NAME in the `proposals` table. The app is deployed on Replit
Autoscale (see .replit), which runs a variable number of instances with ephemeral disks - so the request that
later needs the file (the Google Drive upload) can land on an instance that never had it, or on a fresh one that
replaced it after a restart / scale-down. That produced "intermittent 500s that fix themselves after generating
again" (generating again re-creates the file on whichever instance served the request).

The fix is to keep the generated bytes in PostgreSQL too (the same shared store the Drive token and the proposal
rows already use), keyed by (proposal_id, kind). A .xlsx is 10-100 KB, so a row per proposal is cheap.

SAVING is FAIL-SAFE: a missing table (schema.sql not applied yet) or an unreachable database is logged and reported
as False - keeping a copy must never make /api/generate fail. READING returns None for "nothing stored" (including a
missing table) but lets a connection error propagate, so the caller can tell "gone" from "couldn't look". No file
content or secrets are logged.
"""
from __future__ import annotations

import logging
from pathlib import Path

import psycopg

from app.db import get_connection

_logger = logging.getLogger(__name__)

# One generated workbook is tens of KB; this only guards against a pathological file filling the table.
MAX_FILE_BYTES = 25 * 1024 * 1024


def save_file(proposal_id: str, kind: str, path: Path | str) -> bool:
    """Store (or replace) the bytes of the file at `path` as this proposal's `kind` file. Returns True when stored.
    Never raises."""
    try:
        path = Path(path)
        content = path.read_bytes()
        if not content or len(content) > MAX_FILE_BYTES:
            _logger.warning(
                "proposal file not stored (proposal=%s kind=%s size=%d)", proposal_id, kind, len(content)
            )
            return False
        with get_connection() as conn:
            conn.execute(
                """
                INSERT INTO proposal_files (proposal_id, kind, filename, content, size_bytes)
                VALUES (%s, %s, %s, %s, %s)
                ON CONFLICT (proposal_id, kind) DO UPDATE SET
                    filename = EXCLUDED.filename,
                    content = EXCLUDED.content,
                    size_bytes = EXCLUDED.size_bytes,
                    updated_at = now()
                """,
                (proposal_id, kind, path.name, content, len(content)),
            )
        return True
    except Exception as e:  # noqa: BLE001 - optional durability layer; see module docstring
        _logger.warning(
            "proposal file not stored (proposal=%s kind=%s): %s", proposal_id, kind, type(e).__name__
        )
        return False


def load_bytes(proposal_id: str, kind: str) -> bytes | None:
    """The stored bytes of this proposal's `kind` file, or None when nothing is stored (proposals generated before
    this table existed, or schema.sql not applied yet - so the caller falls back to the local disk / a clear error).

    A database that can't be REACHED is deliberately not swallowed: "nothing stored" and "couldn't look" need
    different answers (410 "regenerate" vs a retryable 503), so connection errors propagate to the caller."""
    try:
        with get_connection() as conn:
            row = conn.execute(
                "SELECT content FROM proposal_files WHERE proposal_id = %s AND kind = %s",
                (proposal_id, kind),
            ).fetchone()
    except psycopg.errors.UndefinedTable:
        _logger.warning("proposal_files table is missing - apply schema.sql (proposal=%s)", proposal_id)
        return None
    if not row or row.get("content") is None:
        return None
    return bytes(row["content"])
